    public string ClassName(Core.Events.GameClass c) => ClassNames.TryGetValue(c, out var n) ? n : "";

    /// <summary>A class id or English class name of the catalogues and profiles ("ranger", "Templar") in this language.</summary>
    public string ClassNameOf(string? id) =>
        string.IsNullOrEmpty(id) ? "" : Enum.TryParse<Core.Events.GameClass>(id, true, out var c) && ClassName(c) is { Length: > 0 } n ? n : char.ToUpperInvariant(id[0]) + id[1..];

