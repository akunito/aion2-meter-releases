    public static readonly string[] Languages = ["en", "es"];

    public static UiText Current { get; private set; } = new();

    /// <summary>"es" or "en"; anything else (the Russian of upstream builds, "ru" in old settings files) falls back to English.</summary>
    public static string Normalize(string? language) => language == "es" ? "es" : "en";

    public static void Use(string? language) => Current = Normalize(language) == "es" ? Es : new UiText();

    public string Code { get; init; } = "en";
