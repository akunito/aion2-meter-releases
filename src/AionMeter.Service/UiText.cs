    /// <summary>"1 h 30 min", "45 min".</summary>
    public string Duration(int minutes)
    {
        var h = minutes / 60;
        var m = minutes % 60;
        if (h == 0) return $"{m} {MinutesShort}";
        return m == 0 ? $"{h} {HoursShort}" : $"{h} {HoursShort} {m} {MinutesShort}";
    }

